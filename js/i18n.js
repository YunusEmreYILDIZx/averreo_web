document.addEventListener('DOMContentLoaded', () => {
  const langBtns = document.querySelectorAll('.lang-btn');
  const allTextNodes = [];

  // Recursive function to get all text nodes
  function getTextNodes(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (node.nodeValue.trim() !== "") {
        allTextNodes.push(node);
      }
    } else {
      // Exclude script and style tags
      if (node.nodeName !== 'SCRIPT' && node.nodeName !== 'STYLE' && !node.classList?.contains('lang-switch')) {
        for (let child of node.childNodes) {
          getTextNodes(child);
        }
      }
    }
  }

  getTextNodes(document.body);

  // Store original Turkish texts
  allTextNodes.forEach(node => {
    node._originalText = node.nodeValue;
  });

  // Handle placeholders in form
  const inputs = document.querySelectorAll('input[placeholder], textarea[placeholder]');
  inputs.forEach(input => {
    input._originalPlaceholder = input.getAttribute('placeholder');
  });

  function setLanguage(lang) {
    // Update active button
    langBtns.forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    if (lang === 'en') {
      allTextNodes.forEach(node => {
        let text = node._originalText;
        // Check for exact match or match ignoring leading/trailing spaces
        let trimmed = text.trim();
        if (translations[trimmed]) {
          node.nodeValue = text.replace(trimmed, translations[trimmed]);
        }
      });
      inputs.forEach(input => {
        let placeholder = input._originalPlaceholder;
        if (translations[placeholder]) {
          input.setAttribute('placeholder', translations[placeholder]);
        }
      });
    } else {
      // Restore TR
      allTextNodes.forEach(node => {
        node.nodeValue = node._originalText;
      });
      inputs.forEach(input => {
        input.setAttribute('placeholder', input._originalPlaceholder);
      });
    }

    localStorage.setItem('averreo_lang', lang);
    if (typeof window.updateCompanyContent === 'function') {
      window.updateCompanyContent(lang);
    }
  }

  // Bind events
  langBtns.forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      setLanguage(btn.dataset.lang);
    });
  });

  // Load from local storage
  const savedLang = localStorage.getItem('averreo_lang') || 'tr';
  if (savedLang === 'en') {
    setLanguage('en');
  }
});
